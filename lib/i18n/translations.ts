// Helper function to get translation
export function t(
  category: keyof typeof translations,
  key: string,
  lang: Language = "en"
): string {
  const categoryObj = translations[category] as Record<string, Record<Language, string>>
  if (categoryObj && categoryObj[key]) {
    return categoryObj[key][lang] || categoryObj[key]["en"]
  }
  return key
}
